describe("help texts", () => {
  it.each(HELP)('documents "pulse-cli %s" with its arguments and options', async (path, lines) => {
    expect(await help(path.split(" "))).toBe(`${lines.join("\n")}\n`)
  })

  it("lists the global options of operation commands with their descriptions", async () => {
    expect(await help(["task", "claim"])).toContain(`\n\n${GLOBAL_OPTIONS.join("\n")}\n\n`)
  })

  it("lists the root options and the config command in the root help", async () => {
    const root = await help([])
    expect(root).toMatch(/\nOptions:\n {2}-V, --version +Print the version\n/)
    expect(root).toMatch(/\n {2}config \[command\] +Manage the config file and its profiles\n/)
  })
})
