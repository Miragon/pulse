import { execFileSync } from "node:child_process"
import fs from "node:fs"
import { describe, expect, it } from "vitest"
import { REPO_ROOT } from "./source-scan.js"

/**
 * Names that fail SILENTLY where they survive: a package someone else owns installs a
 * stranger's code, an image off the GitHub Container Registry pulls nothing (nothing
 * publishes to Docker Hub), and a technical name of the retired operate CLI points to an
 * archived product. No other gate reads them, so this guard reads every tracked text file
 * (and every untracked one git does not ignore) and fails on them.
 */

const RULES = [
  // The images live on GHCR only: a Docker Hub reference (docker.io/…, hub.docker.com/r/…)
  // or a bare name, which Docker resolves on Docker Hub, pulls nothing.
  {
    name: "image off GHCR",
    pattern: /(?<!ghcr\.io\/)(?<![\w.@-])miragon\/pulse-(?:server|cli)(?![\w-])/i,
  },
  // The CLI grew up as its own product, operate, in its own repo. In Pulse it ships under
  // Pulse names only (npm @miragon/pulse-cli, its variables PULSE_CLI_*), so every
  // technical name of the old product is retired: the package (any @miragon/operate-*
  // too), the repo, the image, the Homebrew tap, the docs, the product page, its
  // OPERATE_* variables, its config file and its config directory. The plain word stays
  // ("read and operate your engines", the cockpit's fleet.operate key, Camunda 8 Operate).
  // Only the "Renamed from operate" section may point to the archived repo (ALLOWED).
  { name: "old operate package", pattern: /@miragon\/operate(?!\w)/i },
  { name: "old operate repo", pattern: /(?<![\w.-])miragon\/operate(?![\w-])/i },
  { name: "old operate image", pattern: /ghcr\.io\/miragon\/operate/i },
  { name: "old operate tap", pattern: /miragon\/tap\/operate/i },
  { name: "old operate docs URL", pattern: /miragon\.github\.io\/operate/i },
  { name: "old operate product page", pattern: /miragon\.ai\/tools\/operate/i },
  // A name of its own only: Camunda 8's CAMUNDA_OPERATE_* stays clean.
  { name: "old operate env var", pattern: /\bOPERATE_[A-Z]/ },
  { name: "old operate config file", pattern: /\.operate\.json/ },
  { name: "old operate config dir", pattern: /\.config\/operate/ },
  // The CLI ships as @miragon/pulse-cli: the unscoped package pulse-cli is a stranger's, so
  // `npx pulse-cli` or `npm i -g pulse-cli` installs someone else's code.
  {
    name: "unscoped pulse-cli package",
    pattern:
      /(?:\bnpx|\bbunx|\bdlx)\s+(?:-{1,2}[\w-]+(?:=\S+)?\s+)*pulse-cli(?![\w-])|\b(?:npm|pnpm|yarn|bun)\s+(?:i|install|add)\s+(?:-{1,2}[\w-]+\s+)*pulse-cli(?![\w-])/,
  },
] as const

type RuleName = (typeof RULES)[number]["name"]

/** Never read: history, generated or vendored files, and this guard itself. */
const EXCLUDED: { file: string | RegExp; reason: string }[] = [
  {
    file: "CHANGELOG.md",
    reason: "release-please owns the history; each entry names what shipped",
  },
  { file: "pnpm-lock.yaml", reason: "generated by pnpm install" },
  {
    file: /^docs\/\.vitepress\/miragon\//,
    reason: "the vendored docs kit, compared byte for byte with its source by check:kit",
  },
  {
    file: "apps/mcp-server-camunda7/test/old-names.test.ts",
    reason: "this guard spells out the names it bans",
  },
]

interface Allowance {
  /** Repo-relative path, or a pattern over it. */
  file: string | RegExp
  /** The rules it allows. */
  rules: readonly RuleName[]
  /** Only on lines that match. */
  line?: RegExp
  /** Only under a Markdown heading that matches, up to the next heading of its level or above. */
  section?: RegExp
  reason: string
}

/** Hits that are right where they are. Shrink-only: an entry that covers no hit fails. */
const ALLOWED: Allowance[] = [
  // The VS Code extension (apps/vscode) bundles the last published operate CLI, 0.9.0, and
  // spawns it through its engine-cli wrapper until an in-process engine client replaces both
  // (then these entries go). That release's names are recorded as that release has them.
  {
    file: /^apps\/vscode\/(?:package\.json|scripts\/build\.mjs|test\/adapters\/c7\/support\/engine-cli-binary\.ts)$/,
    rules: ["old operate package", "old operate repo"],
    line: /@miragon\/operate(?:\/dist\/operate\.js)?["']/,
    reason:
      "the extension pins the published operate 0.9.0 (package.json), copies its bundle into dist (build.mjs) and runs it in tests",
  },
  {
    file: /^apps\/vscode\/(?:src\/adapters\/c7\/engine-cli\/running\/engine-cli-environment\.ts|test\/adapters\/c7\/(?:c7-[\w-]+|engine-cli\/[\w-]+)\.test\.ts|test\/adapters\/c7\/fixtures\/error-[\w-]+\.json)$/,
    rules: ["old operate env var"],
    line: /\bOPERATE_(?:URL|OUTPUT|READ_ONLY|CONFIG|AUTH|USERNAME|PASSWORD|TOKEN|TOKEN_COMMAND|PROFILE|VARIABLE)\b/,
    reason:
      "operate 0.9.0 takes target, credentials and the read-only flag from its OPERATE_* variables: the wrapper sets them and drops inherited ones, its tests assert both, the fixtures record its error output",
  },
  {
    file: /^apps\/vscode\/docs\/adr\/(?:c7-adapter|migrations)\.md$/,
    rules: ["old operate package", "old operate repo", "old operate env var"],
    reason:
      "the C7 adapter and migration records say how the extension runs the bundled operate 0.9.0",
  },
  {
    file: "apps/cli/README.md",
    rules: ["old operate repo"],
    section: /^#{2,6} Renamed from operate\b/,
    reason: "the npm README points to the archived repository of operate (up to 0.10.0)",
  },
]

const matches = (file: string, spec: string | RegExp) =>
  typeof spec === "string" ? file === spec : spec.test(file)

/** Every text file git tracks or would add: committed, staged or new and not ignored. */
const textFiles: { file: string; lines: string[] }[] = execFileSync(
  "git",
  ["ls-files", "-z", "--cached", "--others", "--exclude-standard"],
  { cwd: REPO_ROOT, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
)
  .split("\0")
  .filter((file) => file !== "" && !EXCLUDED.some((entry) => matches(file, entry.file)))
  .flatMap((file) => {
    const abs = `${REPO_ROOT}/${file}`
    if (!fs.existsSync(abs) || !fs.statSync(abs).isFile()) return [] // deleted, not yet staged
    const bytes = fs.readFileSync(abs)
    if (bytes.subarray(0, 8000).includes(0)) return [] // binary: fonts, images, jars
    return [{ file, lines: bytes.toString("utf8").split("\n") }]
  })

interface Hit {
  file: string
  /** 1-based; 0 is the path itself. */
  line: number
  text: string
  rule: RuleName
}

const rulesMatching = (text: string): RuleName[] =>
  RULES.filter((rule) => rule.pattern.test(text)).map((rule) => rule.name)

/** The 1-based lines under each heading that matches `heading`, fenced code skipped as headings. */
function sectionLines(lines: string[], heading: RegExp): Set<number> {
  const inside = new Set<number>()
  let level: number | undefined
  let fenced = false
  lines.forEach((text, index) => {
    if (/^\s*```/.test(text)) fenced = !fenced
    const depth = fenced ? undefined : /^(#{1,6})\s/.exec(text)?.[1]?.length
    if (depth !== undefined && level !== undefined && depth <= level) level = undefined
    if (depth !== undefined && heading.test(text)) level = depth
    if (level !== undefined) inside.add(index + 1)
  })
  return inside
}

function allows(entry: Allowance, hit: Hit, lines: string[]): boolean {
  if (!matches(hit.file, entry.file) || !entry.rules.includes(hit.rule)) return false
  if (entry.line && !entry.line.test(hit.text)) return false
  return entry.section ? sectionLines(lines, entry.section).has(hit.line) : true
}

const hits: { hit: Hit; lines: string[] }[] = textFiles.flatMap(({ file, lines }) =>
  [file, ...lines].flatMap((text, line) =>
    rulesMatching(text).map((rule) => ({ hit: { file, line, text: text.trim(), rule }, lines })),
  ),
)

const where = ({ file, line, text, rule }: Hit) =>
  `${file}${line > 0 ? `:${line}` : ""} [${rule}] ${text.slice(0, 160)}`

describe("old and foreign names", () => {
  it("reads the repo", () => {
    expect(textFiles.some(({ file }) => file === "CLAUDE.md")).toBe(true)
    expect(textFiles.length).toBeGreaterThan(500)
  })

  it("no file names an old name outside its allowance", () => {
    const stale = hits
      .filter(({ hit, lines }) => !ALLOWED.some((entry) => allows(entry, hit, lines)))
      .map(({ hit }) => where(hit))
    expect(stale).toEqual([])
  })

  it.each(ALLOWED.map((entry) => [entry.reason, entry] as const))(
    "the allowance still covers a hit: %s",
    (_reason, entry) => {
      expect(hits.some(({ hit, lines }) => allows(entry, hit, lines))).toBe(true)
    },
  )
})

