/**
 * The conformance cases of the wire: redirects, the network, the deadline and the size cap.
 */
import { connection, INSTANCE, LOGIN_PAGE, QUERY, READ, WRITE } from "./parts.js"
import type { TransportCase } from "./types.js"

const SHORT = connection({ timeoutMs: 300 })
const CAPPED = connection({ maxAnswerBytes: 1024 })

export const WIRE_CASES: readonly TransportCase[] = [
  {
    name: "redirect",
    about: "a 302 to a login page fails, names the target without its query and follows nothing",
    connection: connection(),
    request: READ,
    answers: [{ status: 302, headers: { Location: LOGIN_PAGE } }],
    expect: {
      outcome: "redirect",
      status: 302,
      mayHaveApplied: false,
      sent: 1,
      contains: ["https://sso.example.com/realms/ops/protocol/openid-connect/auth"],
      never: ["client_id=engine", "state=4711"],
    },
  },
  {
    name: "redirect-of-a-write",
    about: "a 303 to a write is no answer: the write is not turned into a GET",
    connection: connection(),
    request: WRITE,
    answers: [{ status: 303, headers: { Location: "/login" } }],
    expect: { outcome: "redirect", status: 303, mayHaveApplied: false, sent: 1 },
  },
  {
    name: "redirect-unparsable-location",
    about: "a Location that does not parse is still a redirect, without a target",
    connection: connection(),
    request: READ,
    answers: [{ status: 302, headers: { Location: "http://[" } }],
    expect: { outcome: "redirect", status: 302, mayHaveApplied: false, sent: 1 },
  },
  {
    name: "deadline-exceeded",
    about: "an engine that never answers fails a read at the deadline",
    connection: SHORT,
    request: READ,
    answers: [{ hang: "headers" }],
    expect: { outcome: "deadline", mayHaveApplied: false, sent: 1 },
  },
  {
    name: "deadline-exceeded-write",
    about: "a write the deadline cut may have been applied",
    connection: SHORT,
    request: WRITE,
    answers: [{ hang: "headers" }],
    expect: { outcome: "deadline", mayHaveApplied: true, sent: 1 },
  },
  {
    name: "deadline-exceeded-reading-post",
    about: "a POST the caller marks as a read applied nothing",
    connection: SHORT,
    request: QUERY,
    answers: [{ hang: "headers" }],
    expect: { outcome: "deadline", mayHaveApplied: false, sent: 1 },
  },
  {
    name: "deadline-exceeded-in-the-body",
    about: "the deadline holds to the last byte: headers in time, a body that stalls",
    connection: SHORT,
    request: READ,
    answers: [{ hang: "body" }],
    expect: { outcome: "deadline", mayHaveApplied: false, sent: 1 },
  },
  {
    name: "deadline-exceeded-by-a-slow-body",
    about: "a body that trickles past the deadline fails at the deadline",
    connection: SHORT,
    request: READ,
    answers: [{ ...INSTANCE, trickle: { chunks: 8, everyMs: 100 } }],
    expect: { outcome: "deadline", mayHaveApplied: false, sent: 1 },
  },
  {
    name: "slow-body-within-the-deadline",
    about: "a body that trickles but ends before the deadline is an answer",
    connection: connection({ timeoutMs: 2_000 }),
    request: READ,
    answers: [{ ...INSTANCE, trickle: { chunks: 4, everyMs: 50 } }],
    expect: { outcome: "answered", status: 200, sent: 1, contains: ["pi-1"] },
  },
  {
    name: "cancelled-by-the-caller",
    about: "the caller aborts a read the engine does not answer: it ends at once, applying nothing",
    connection: connection(),
    request: { ...READ, cancelAfterMs: 100 },
    answers: [{ hang: "headers" }],
    expect: { outcome: "cancelled", mayHaveApplied: false, sent: 1 },
  },
  {
    name: "cancel-of-a-write-ignored",
    about: "the caller's abort does not cut a write that left: it runs on to its answer",
    connection: connection({ timeoutMs: 2_000 }),
    request: { ...WRITE, cancelAfterMs: 30 },
    answers: [{ ...INSTANCE, trickle: { chunks: 3, everyMs: 60 } }],
    expect: { outcome: "answered", status: 200, sent: 1, contains: ["pi-1"] },
  },
  {
    name: "unreachable",
    about: "a closed port: nothing was sent",
    connection: connection({ endpoint: "closed-port" }),
    request: READ,
    answers: [],
    expect: { outcome: "unreachable", mayHaveApplied: false, sent: 0 },
  },
  {
    name: "unreachable-write",
    about: "a write to a closed port was not sent, so it applied nothing",
    connection: connection({ endpoint: "closed-port" }),
    request: WRITE,
    answers: [],
    expect: { outcome: "unreachable", mayHaveApplied: false, sent: 0 },
  },
  {
    name: "tls-failure",
    about: "a self-signed certificate stops the handshake before any request",
    connection: connection({ endpoint: "self-signed-tls" }),
    request: READ,
    answers: [INSTANCE],
    expect: { outcome: "tls", mayHaveApplied: false, sent: 0 },
  },
  {
    name: "tls-failure-write",
    about: "a write the handshake stopped applied nothing",
    connection: connection({ endpoint: "self-signed-tls" }),
    request: WRITE,
    answers: [INSTANCE],
    expect: { outcome: "tls", mayHaveApplied: false, sent: 0 },
  },
  {
    name: "dns-failure",
    about: "a host no resolver answers: nothing was sent",
    connection: connection({ endpoint: "unresolvable-host" }),
    request: READ,
    answers: [],
    expect: { outcome: "dns", mayHaveApplied: false, sent: 0 },
  },
  {
    name: "connection-reset",
    about: "a connection closed before the answer fails a read without a caveat",
    connection: connection(),
    request: READ,
    answers: [{ reset: true }],
    expect: { outcome: "connection", mayHaveApplied: false, sent: 1 },
  },
  {
    name: "connection-reset-write",
    about: "a write whose connection closed after it arrived may have been applied",
    connection: connection(),
    request: WRITE,
    answers: [{ reset: true }],
    expect: { outcome: "connection", mayHaveApplied: true, sent: 1 },
  },
  {
    name: "too-large-response",
    about: "a streamed body one byte over the cap fails",
    connection: CAPPED,
    request: READ,
    answers: [{ bytes: 1025 }],
    expect: { outcome: "too-large", mayHaveApplied: false, sent: 1 },
  },
  {
    name: "too-large-announced",
    about: "an announced length over the cap fails before the body",
    connection: CAPPED,
    request: READ,
    answers: [{ bytes: 2048, announce: true }],
    expect: { outcome: "too-large", mayHaveApplied: false, sent: 1 },
  },
  {
    name: "too-large-write",
    about: "a write whose answer was too large may have been applied",
    connection: CAPPED,
    request: WRITE,
    answers: [{ bytes: 1025 }],
    expect: { outcome: "too-large", mayHaveApplied: true, sent: 1 },
  },
  {
    name: "at-the-size-cap",
    about: "a body of exactly the cap is an answer",
    connection: CAPPED,
    request: READ,
    answers: [{ bytes: 1024, headers: { "Content-Type": "text/plain" } }],
    expect: { outcome: "answered", status: 200, sent: 1 },
  },
]
